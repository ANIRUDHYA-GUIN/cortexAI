import PDFDocument from "pdfkit";

export const generatePdf = async (data) => {
    return new Promise((resolve, reject) => {
        try {
            const doc = new PDFDocument({
                size: "A4",
                margin: 50,
                bufferPages: true,
                info: {
                    Author: "CortexAI",
                    Title: data?.title || "CortexAI Document",
                    Creator: "CortexAI"
                }
            });

            const chunks = [];

            // Collect PDF data
            doc.on("data", (chunk) => {
                chunks.push(chunk);
            });

            // Return the complete PDF buffer
            doc.on("end", () => {
                resolve(Buffer.concat(chunks));
            });

            // Handle PDF generation errors
            doc.on("error", (error) => {
                reject(error);
            });

            // Title
            doc.fillColor("#111827")
                .font("Helvetica-Bold")
                .fontSize(26)
                .text(data?.title || "Untitled Document", {
                    align: "center"
                });

            // Subtitle
            if (data?.subtitle) {
                doc.moveDown(0.5);

                doc.fillColor("#6B7280")
                    .font("Helvetica")
                    .fontSize(12)
                    .text(data.subtitle, {
                        align: "center"
                    });
            }

            doc.moveDown(2);

            // Content sections
            for (const section of data?.sections || []) {
                // Section heading
                if (section?.heading) {
                    doc.fillColor("#111827")
                        .font("Helvetica-Bold")
                        .fontSize(17)
                        .text(section.heading, {
                            continued: false
                        });

                    doc.moveDown(0.5);
                }

                // Section bullet points
                for (const point of section?.points || []) {
                    doc.fillColor("#374151")
                        .font("Helvetica")
                        .fontSize(11)
                        .text(`• ${String(point)}`, {
                            lineGap: 5,
                            paragraphGap: 4
                        });
                }

                doc.moveDown();
            }

            // Footer
            doc.moveDown();

            doc.fillColor("#9CA3AF")
                .font("Helvetica")
                .fontSize(9)
                .text("Generated by CortexAI", {
                    align: "center"
                });

            // Finish PDF generation
            doc.end();

        } catch (error) {
            reject(error);
        }
    });
};
